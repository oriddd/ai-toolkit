#!/usr/bin/env python3
"""Regenerate REGISTRY.md and the BACKEND_GUILD.md adoption matrix from
the frontmatter of every SKILL.md.
Usage:
    python3 tools/build-indexes.py             # rewrite files in place
    python3 tools/build-indexes.py --check     # exit 1 if files would change (CI)
"""
import os, re, sys, glob, json, argparse, hashlib
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DOCS = os.path.join(ROOT, "docs")
FM_RE = re.compile(r"^---\n(.*?)\n---\n", re.S)
def parse_fm(text):
    m = FM_RE.match(text)
    if not m:
        return {}
    fm = m.group(1)
    out = {}
    lines = fm.splitlines()
    i = 0
    while i < len(lines):
        line = lines[i]
        mm = re.match(r"^([a-zA-Z_]+):\s*(.*)$", line)
        if not mm:
            i += 1
            continue
        k, v = mm.group(1), mm.group(2).strip()
        # Handle YAML block scalars: ">" (folded) and "|" (literal)
        if v in ('>', '|'):
            parts = []
            i += 1
            while i < len(lines) and (lines[i].startswith('  ') or lines[i].startswith('\t')):
                parts.append(lines[i].strip())
                i += 1
            out[k] = ' '.join(parts) if v == '>' else '\n'.join(parts)
            continue
        if v.startswith("[") and v.endswith("]"):
            inner = v[1:-1].strip()
            out[k] = [x.strip() for x in inner.split(",") if x.strip()] if inner else []
        elif v in ("true", "false"):
            out[k] = (v == "true")
        else:
            out[k] = v
        i += 1
    return out
def collect():
    skills = []
    for p in sorted(glob.glob(os.path.join(ROOT, "plugins", "*", "skills", "*", "SKILL.md"))):
        folder = os.path.basename(os.path.dirname(p))
        fm = parse_fm(open(p, encoding="utf-8").read())
        fm["_folder"] = folder
        fm["_plugin"] = p.split(os.sep)[-4]
        skills.append(fm)
    return skills
def render_registry(skills):
    out  = ["# Skills Registry\n"]
    out += ["<!-- AUTO-GENERATED by build-indexes.py — DO NOT EDIT BY HAND. -->",
            "<!-- Re-run: python3 tools/build-indexes.py -->\n",
            "Machine-readable index of every skill in this catalogue.",
            "Used by agents to pick a skill and by `validate-skills.sh` to",
            "enforce that every skill has a home in this file.\n",
            "## Totals\n",
            f"| Tier | Count |", f"| --- | --- |",
            f"| Public | **{len(skills)}** |\n",
            "## Skills\n",
            "Legend — **T** = ships templates; **HITL** = human-in-the-loop;",
            "**Tier** = MUST / SHOULD / MAY adoption tier.\n",
            "| Skill | Tier | T | HITL | Applies to | Depends on | One-line summary |",
            "| --- | :-: | :-: | :-: | --- | --- | --- |"]
    for s in skills:
        f = s["_folder"]
        tier = s.get("tier","?").upper()
        t   = "✓" if s.get("ships_templates") else ""
        h   = "✓" if s.get("hitl") else ""
        apps = ", ".join(s.get("applies_to",[])) or "—"
        deps = ", ".join(f"`{d}`" for d in s.get("depends_on",[])) or "—"
        desc = s.get("description","").split(".")[0].strip()[:140]
        out.append(f"| [`{f}`](../plugins/{s['_plugin']}/skills/{f}/SKILL.md) | {tier} | {t} | {h} | {apps} | {deps} | {desc}. |")
    out.append("")
    return "\n".join(out) + "\n"
def render_matrix(skills):
    """Render the MUST/SHOULD/MAY adoption matrix snippet for BACKEND_GUILD.md."""
    by_tier = {"must":[], "should":[], "foundational":[], "may":[]}
    for s in skills:
        by_tier.setdefault(s.get("tier","may"), []).append(s)
    lines = []
    titles = {"must":"MUST — every service",
              "should":"SHOULD — when the service has the feature",
              "foundational":"FOUNDATIONAL — patterns other skills build on",
              "may":"MAY — useful but optional"}
    for tier in ("must","should","foundational","may"):
        bucket = by_tier[tier]
        lines.append(f"### {titles[tier]} ({len(bucket)})\n")
        lines.append("| Skill | One-line summary |")
        lines.append("| --- | --- |")
        for s in bucket:
            f = s["_folder"]
            desc = s.get("description","").split(".")[0].strip()[:160]
            lines.append(f"| [`{f}`](../plugins/{s['_plugin']}/skills/{f}/SKILL.md) | {desc}. |")
        lines.append("")
    return "\n".join(lines)
def render_dep_graph(skills):
    """Mermaid graph of inter-skill dependencies, snippet for BACKEND_GUILD.md."""
    lines = ["```mermaid", "graph LR"]
    for s in skills:
        f = s["_folder"]
        for d in s.get("depends_on", []):
            lines.append(f"  {d.replace('-','_')} --> {f.replace('-','_')}")
    lines.append("```")
    return "\n".join(lines)
def splice(path, marker, payload):
    """Replace the region between <!-- BEGIN AUTO:<marker> --> and <!-- END AUTO:<marker> -->."""
    body = open(path, encoding="utf-8").read()
    begin = f"<!-- BEGIN AUTO:{marker} -->"
    end   = f"<!-- END AUTO:{marker} -->"
    pat = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    block = f"{begin}\n{payload}\n{end}"
    if pat.search(body):
        new = pat.sub(block, body)
    else:
        new = body.rstrip() + "\n\n" + block + "\n"
    return new

GENERATED_NOTE = ("<!-- AUTO-GENERATED by tools/build-indexes.py from {src} — DO NOT EDIT BY HAND. "
                  "Edit the source document and re-run: python3 tools/build-indexes.py -->")
def section(text, start_prefix):
    """Return the '## ' section whose heading starts with start_prefix (up to the next '## ')."""
    m = re.search(r"^## " + re.escape(start_prefix) + r".*?(?=^## |\Z)", text, re.S | re.M)
    return m.group(0).rstrip() + "\n" if m else ""
PATTERN_SELECTION_REFERENCES = [
    ("refactoring-path-and-examples.md", "Red flags, refactoring path and examples",
     ["Red Flags", "The Refactoring Path", "Examples from Real World"],
     "judging whether a design is over-engineered, planning a refactor, or looking for worked examples"),
    ("anti-patterns.md", "Anti-patterns to avoid", ["Anti-Patterns to Avoid"], "reviewing a design for anti-patterns"),
]
def split_sections(text):
    """Split markdown into (preamble, ['## ' sections]) — headings inside code fences are ignored."""
    pre, secs, fence = [], [], False
    for line in text.split("\n"):
        if line.startswith("```"):
            fence = not fence
        if not fence and line.startswith("## "):
            secs.append([line])
        elif secs:
            secs[-1].append(line)
        else:
            pre.append(line)
    return "\n".join(pre), ["\n".join(s) for s in secs]
def render_generated_skills():
    """Ship repo-level standards documents inside the plugins so installed agents can load them."""
    out = {}
    bg = os.path.join(DOCS, "BACKEND_GUILD.md")
    if os.path.exists(bg):
        t = open(bg, encoding="utf-8").read()
        body = section(t, "2. Adoption sequence") + "\n" + section(t, "4. Guild non-negotiables")
        fm = ("---\nname: golden-path\n"
              "description: The Java / Spring Boot golden path — the apply-order of the skills and the 24 non-negotiables every diff must satisfy. "
              "Use when planning a change (which skills, in which order), when validating a finished diff, and when reviewing a PR against the non-negotiables.\n"
              "tier: must\napplies_to: [rest, event, scheduler, library, monolith]\ndepends_on: [code-structure, quality-review]\n"
              "ships_templates: false\nhitl: false\nversion: 1.0\nlast_reviewed: 2026-11-03\n---\n\n")
        out[os.path.join(ROOT, "plugins", "ai-toolkit-java-quality", "skills", "golden-path", "SKILL.md")] = (
            fm + "# Golden Path Skill\n\n" + GENERATED_NOTE.format(src="docs/BACKEND_GUILD.md §2 and §4") + "\n\n" + body)
    ps = os.path.join(DOCS, "PATTERN_SELECTION_GUIDE.md")
    if os.path.exists(ps):
        t = open(ps, encoding="utf-8").read()
        fm = ("---\nname: pattern-selection\n"
              "description: >\n  Java / Spring Boot: choose the smallest pattern that fits the actual scale — scale-based decision tables for external clients, operations and layers, red flags of over-engineering, and when to ask the developer. "
              "Use before introducing any new layer, pattern, client package or abstraction, and when a design feels heavier than the problem.\n"
              "tier: must\napplies_to: [rest, event, scheduler, library, monolith]\ndepends_on: [code-structure, external-client]\n"
              "ships_templates: false\nhitl: true\nversion: 1.0\nlast_reviewed: 2026-11-03\n---\n\n")
        skill_dir = os.path.join(ROOT, "plugins", "ai-toolkit-java-design", "skills", "pattern-selection")
        pre, secs = split_sections(t)
        moved = {}
        for fname, title, prefixes, when in PATTERN_SELECTION_REFERENCES:
            picked = [s for s in secs if any(s.startswith("## " + p) for p in prefixes)]
            moved[fname] = picked
            out[os.path.join(skill_dir, "references", fname)] = (
                "# Pattern Selection — " + title + "\n\nPart of the [`pattern-selection`](../SKILL.md) skill. "
                + GENERATED_NOTE.format(src="docs/PATTERN_SELECTION_GUIDE.md") + "\n\n"
                + "\n\n".join(s.rstrip() for s in picked) + "\n")
        moved_blocks = {id(s) for picked in moved.values() for s in picked}
        rows = "".join("| " + ", ".join(p for p in prefixes) + " | " + when + " | [`" + fname + "`](./references/" + fname + ") |\n"
                       for fname, _, prefixes, when in PATTERN_SELECTION_REFERENCES)
        ref_map = ("## Reference map — load only the part you are working on\n\n"
                   "These sections live in `references/` so this file stays small. Read only the file you need.\n\n"
                   "| Sections | Load when | File |\n| --- | --- | --- |\n" + rows)
        kept, placed = [], False
        for s in secs:
            if id(s) in moved_blocks:
                if not placed:
                    kept.append(ref_map)
                    placed = True
            else:
                kept.append(s.rstrip() + "\n")
        out[os.path.join(skill_dir, "SKILL.md")] = (
            fm + GENERATED_NOTE.format(src="docs/PATTERN_SELECTION_GUIDE.md") + "\n\n" + pre.rstrip() + "\n\n" + "\n".join(kept))
    return out

def render_shipped_names():
    """Names of every shipped skill and agent — used by the stale-copy warning and remove-old-copies.sh."""
    lines = []
    for p in sorted(glob.glob(os.path.join(ROOT, "plugins", "*", "skills", "*", "SKILL.md"))):
        lines.append("skill:" + os.path.basename(os.path.dirname(p)))
    for p in sorted(glob.glob(os.path.join(ROOT, "plugins", "*", "agents", "*.md"))):
        lines.append("agent:" + os.path.basename(p)[:-3])
    return "\n".join(sorted(set(lines))) + "\n"
def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true",
                    help="Exit non-zero if any file would change.")
    args = ap.parse_args()
    generated = render_generated_skills()
    changed = []
    for path, content in generated.items():
        existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if existing != content:
            changed.append(os.path.relpath(path, ROOT))
            if not args.check:
                os.makedirs(os.path.dirname(path), exist_ok=True)
                open(path, "w", encoding="utf-8").write(content)
    skills = collect()
    targets = {
        os.path.join(ROOT, "plugins", "ai-toolkit-workflow", "hooks", "shipped-names.txt"): render_shipped_names(),
        os.path.join(DOCS, "REGISTRY.md"): render_registry(skills),
    }
    # Splice into BACKEND_GUILD.md
    bg = os.path.join(DOCS, "BACKEND_GUILD.md")
    if os.path.exists(bg):
        new_bg = splice(bg, "matrix", render_matrix(skills))
        new_bg = splice_text(new_bg, "graph", render_dep_graph(skills))
        targets[bg] = new_bg
    for path, content in targets.items():
        existing = open(path, encoding="utf-8").read() if os.path.exists(path) else ""
        if existing != content:
            changed.append(os.path.relpath(path))
            if not args.check:
                open(path, "w", encoding="utf-8").write(content)
    if args.check:
        if changed:
            print("Generated docs are out of date:", *changed, sep="\n  ")
            print("\nRun: python3 tools/build-indexes.py")
            sys.exit(1)
        print("Generated docs are up to date.")
    else:
        if changed:
            print("Regenerated:", *changed, sep="\n  ")
        else:
            print("No changes — already up to date.")
def splice_text(body, marker, payload):
    """Same as splice() but operates on a string (not a file path)."""
    begin = f"<!-- BEGIN AUTO:{marker} -->"
    end   = f"<!-- END AUTO:{marker} -->"
    pat = re.compile(re.escape(begin) + r".*?" + re.escape(end), re.S)
    block = f"{begin}\n{payload}\n{end}"
    if pat.search(body):
        return pat.sub(block, body)
    return body.rstrip() + "\n\n" + block + "\n"
if __name__ == "__main__":
    main()
